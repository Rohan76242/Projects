"""Z3RO — Experiment Execution Runner.

Implements Section 7:
- Converts approved strategies into micro-scale, bounded experiments.
- Enforces single-transaction and daily spending limits.
- Executes via authorized tools respecting the rate-limiter.
"""

import time
import uuid
from dataclasses import dataclass, field
from typing import Dict, Any, Optional

from z3ro.autonomy.strategy import Strategy, StrategyLifecycle
from z3ro.economy.limits import limits_manager
from z3ro.tools.browser import browser_tool
from z3ro.tools.files import files_tool
from z3ro.memory.experiences import experience_store


@dataclass
class ExperimentResult:
    experiment_id: str
    strategy_id: str
    success: bool
    actual_cost: float
    time_elapsed_sec: float
    output_summary: str
    artifact_path: Optional[str] = None
    error: Optional[str] = None


class ExperimentRunner:
    """Safely conducts micro-experiments for candidate strategies."""

    def run_experiment(self, strategy: Strategy) -> ExperimentResult:
        """Execute a controlled test of the given strategy within safety bounds."""
        exp_id = f"exp_{uuid.uuid4().hex[:8]}"
        t0 = time.time()
        strategy.state = StrategyLifecycle.EXPERIMENTING

        # 1. Check spending & rate limits before running
        can_exec, reason = limits_manager.check_can_execute(
            capability=strategy.target_capability,
            cost=strategy.estimated_cost,
        )
        if not can_exec:
            strategy.state = StrategyLifecycle.EVALUATED
            return ExperimentResult(
                experiment_id=exp_id,
                strategy_id=strategy.strategy_id,
                success=False,
                actual_cost=0.0,
                time_elapsed_sec=time.time() - t0,
                output_summary="Failed safety limits pre-flight check.",
                error=reason,
            )

        # 2. Execute according to capability
        actual_cost = strategy.estimated_cost
        output_summary = ""
        artifact_path = None
        success = True

        try:
            if strategy.target_capability == "web_research":
                # Simulated or real research query
                search_res = browser_tool.search_web(strategy.name)
                output_summary = f"Synthesized research query '{strategy.name}'. Found {len(search_res.get('related_snippets', []))} insights."
                experience_store.record_experience(
                    strategy_id=strategy.strategy_id,
                    experiment_id=exp_id,
                    tool_name="browser.search_web",
                    action_input=strategy.name,
                    action_output=output_summary,
                    success=True,
                )

            elif strategy.target_capability == "draft_content_code":
                filename = f"report_{strategy.strategy_id}.md"
                content = f"# {strategy.name}\n\nGenerated by Z3RO Autonomous Agent.\n\nDescription: {strategy.description}\n"
                write_res = files_tool.write_file(filename, content)
                if write_res.get("success"):
                    artifact_path = write_res.get("path")
                    output_summary = f"Drafted structured artifact to {filename} ({write_res.get('bytes_written')} bytes)."
                else:
                    success = False
                    output_summary = f"File draft failed: {write_res.get('error')}"

                experience_store.record_experience(
                    strategy_id=strategy.strategy_id,
                    experiment_id=exp_id,
                    tool_name="files.write_file",
                    action_input=filename,
                    action_output=output_summary,
                    success=success,
                )

            else:
                output_summary = f"Conducted capability test for '{strategy.target_capability}'."

            limits_manager.record_action_executed(cost=actual_cost)

        except Exception as e:
            success = False
            output_summary = f"Experiment encountered unexpected error: {e}"
            limits_manager.record_action_failed_or_rejected()

        elapsed = time.time() - t0
        return ExperimentResult(
            experiment_id=exp_id,
            strategy_id=strategy.strategy_id,
            success=success,
            actual_cost=actual_cost,
            time_elapsed_sec=elapsed,
            output_summary=output_summary,
            artifact_path=artifact_path,
        )


# Global experiment runner singleton
experiment_runner = ExperimentRunner()
